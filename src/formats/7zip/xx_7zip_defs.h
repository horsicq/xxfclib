#define XX_7ZIP_METHOD_RISCV UINT64_C(0x0B)
#define XX_7ZIP_METHOD_PPMD7 UINT64_C(0x030401)
#define XX_7ZIP_METHOD_BZIP2 UINT64_C(0x040202)
