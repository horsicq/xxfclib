#define XX_7ZIP_METHOD_COPY  UINT64_C(0x00)
#define XX_7ZIP_METHOD_LZMA2 UINT64_C(0x21)
#define XX_7ZIP_METHOD_LZMA  UINT64_C(0x030101)
#define XX_7ZIP_METHOD_BCJ   UINT64_C(0x03030103)
#define XX_7ZIP_METHOD_BCJ2  UINT64_C(0x0303011B)
#define XX_7ZIP_METHOD_PPC   UINT64_C(0x03030205)
#define XX_7ZIP_METHOD_IA64  UINT64_C(0x03030401)
#define XX_7ZIP_METHOD_ARM   UINT64_C(0x03030501)
#define XX_7ZIP_METHOD_ARMT  UINT64_C(0x03030701)
#define XX_7ZIP_METHOD_SPARC UINT64_C(0x03030805)
/* ARM64 is the compact method id used by current 7-Zip releases. */
#define XX_7ZIP_METHOD_ARM64 UINT64_C(0x0A)
