/* xx_cpio_extractor.c - search raw data for CPIO.
 *
 * Scans for:
 *   30 37 30 37 30 31 at +0  ("070701")
 *   30 37 30 37 30 32 at +0  ("070702")
 *   30 37 30 37 30 37 at +0  ("070707")
 *   30 37 30 37 32 37 at +0  ("070727")
 *   C7 71 at +0  (".q")
 *   71 C7 at +0  ("q.")
 *   19 9E 54 4C at +0  ("..TL")
 * Offset 0 is always tried as well.
 * Each candidate must be accepted by the cpio reader, which also measures it,
 * and named by the detector, both on a view that starts at the candidate.
 * See xx_format_extractor_engine.h.
 *
 * GENERATED by gen_extractors.py from the detector's prefilters.
 */

#include "../xx_format_extractor_engine.h"
#include "xxfclib/formats/cpio/xx_cpio.h"

static const uint8_t k_anchor0[] = { 0x30, 0x37, 0x30, 0x37, 0x30, 0x31 };
static const uint8_t k_anchor1[] = { 0x30, 0x37, 0x30, 0x37, 0x30, 0x32 };
static const uint8_t k_anchor2[] = { 0x30, 0x37, 0x30, 0x37, 0x30, 0x37 };
static const uint8_t k_anchor3[] = { 0x30, 0x37, 0x30, 0x37, 0x32, 0x37 };
static const uint8_t k_anchor4[] = { 0xC7, 0x71 };
static const uint8_t k_anchor5[] = { 0x71, 0xC7 };
static const uint8_t k_anchor6[] = { 0x19, 0x9E, 0x54, 0x4C };

static const xx_format_search_anchor k_anchors[] = {
    { k_anchor0, sizeof(k_anchor0), 0U },
    { k_anchor1, sizeof(k_anchor1), 0U },
    { k_anchor2, sizeof(k_anchor2), 0U },
    { k_anchor3, sizeof(k_anchor3), 0U },
    { k_anchor4, sizeof(k_anchor4), 0U },
    { k_anchor5, sizeof(k_anchor5), 0U },
    { k_anchor6, sizeof(k_anchor6), 0U },
};

static const xx_file_type_t k_types[] = { XX_FILE_TYPE_CPIO };

static Abstractformat *xx_cpio_search_open(xx_io_device *window) {
    xx_cpio *reader = xx_cpio_create(window, 0);
    return reader ? &reader->format : NULL;
}

static void xx_cpio_search_close(Abstractformat *format) {
    /* The format is the first member, so this is the reader itself. */
    xx_cpio_free((xx_cpio *)format);
}

static const xx_format_search_desc k_desc = {
    k_types, sizeof(k_types) / sizeof(k_types[0]),
    k_anchors, sizeof(k_anchors) / sizeof(k_anchors[0]),
    xx_cpio_search_open, xx_cpio_search_close
};

static xx_format_search_state *xx_cpio_create_format_search(
    xx_format_extractor *self, xx_io_device *device, const xx_list_s *options,
    xx_pd_struct *pd) {
    (void)self;
    return xx_format_search_create(&k_desc, device, options, pd);
}

static const xx_format_search_info *xx_cpio_get_current_format_info(
    xx_format_extractor *self, xx_format_search_state *state) {
    (void)self;
    return xx_format_search_current(state);
}

static bool xx_cpio_format_search_find_next(xx_format_extractor *self,
                                          xx_format_search_state *state,
                                          xx_pd_struct *pd) {
    (void)self;
    return xx_format_search_find_next(state, pd);
}

static void xx_cpio_free_format_search(xx_format_extractor *self,
                                     xx_format_search_state *state) {
    (void)self;
    xx_format_search_free(state);
}

xx_format_extractor xx_cpio_extractor = {
    xx_cpio_create_format_search,
    xx_cpio_get_current_format_info,
    xx_cpio_format_search_find_next,
    xx_cpio_free_format_search
};
