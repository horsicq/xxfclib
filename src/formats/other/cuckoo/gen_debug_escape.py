"""Generate xx_cuckoo_yx_debug_escape.inc: the Unicode scalar ranges that
Rust's str-Debug escaping (as compiled into official yr 1.23.0, used by serde's
Unexpected::Str rendering in cuckoo diagnostics) escapes as \\u{...}.

If rust_debug_escape_ranges.txt (produced by probing official yr) sits next to
this script it is used directly; otherwise the script probes official yr
itself (slow, ~3 minutes).
"""
import json, pathlib, subprocess, sys

HERE = pathlib.Path(__file__).parent
RANGES_TXT = HERE / 'rust_debug_escape_ranges.txt'
OUT = HERE / 'xx_cuckoo_yx_debug_escape.inc'
YR = pathlib.Path(r'F:/ownCloud_build/XCYara/.upstream/yr/yr.exe')

def probe_ranges():
    sep = chr(1)
    sep_esc = json.dumps(sep)[1:-1]

    def probe_batch(cps):
        parts = [json.dumps(chr(cp), ensure_ascii=False)[1:-1] for cp in cps]
        doc = '{"behavior":"' + sep_esc + sep_esc.join(parts) + sep_esc + '"}'
        (HERE / '_gen_batch.json').write_bytes(doc.encode('utf-8'))
        p = subprocess.run([str(YR), 'scan', '-x', 'cuckoo=_gen_batch.json',
                            '_gen_rule.yar', '_gen_data.bin'],
                           capture_output=True, timeout=60)
        out = p.stderr.decode('utf-8', 'replace')
        marker = 'invalid type: string "'
        i = out.find(marker) + len(marker)
        j = out.rfind('", expected struct BehaviorJson')
        chunks = out[i:j].split('\\u{1}')[1:-1]
        assert len(chunks) == len(cps)
        return chunks

    (HERE / '_gen_rule.yar').write_text(
        'import "cuckoo"\nrule t { condition: cuckoo.sync.mutex(/m/) != 0 }\n')
    (HERE / '_gen_data.bin').write_bytes(b'x')
    cps = [cp for cp in range(0x80, 0x110000)
           if not (0xD800 <= cp <= 0xDFFF)]
    escaped = []
    for at in range(0, len(cps), 400):
        for cp, rendered in zip(cps[at:at + 400],
                                probe_batch(cps[at:at + 400])):
            if rendered != chr(cp):
                escaped.append(cp)
    for f in ('_gen_batch.json', '_gen_rule.yar', '_gen_data.bin'):
        (HERE / f).unlink(missing_ok=True)
    ranges = []
    for cp in escaped:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ranges

def main():
    if RANGES_TXT.exists():
        ranges = [list(map(int, line.split()))
                  for line in RANGES_TXT.read_text().splitlines() if line.strip()]
    else:
        ranges = probe_ranges()
    lines = []
    lines.append('/* Generated by gen_debug_escape.py - do not edit by hand.')
    lines.append(' *')
    lines.append(' * serde_json renders unexpected string values with Rust\'s')
    lines.append(' * str Debug escaping (\\u{...} for non-printable and')
    lines.append(' * grapheme-extended scalars, \\0 for NUL, short escapes for')
    lines.append(' * \\t \\r \\n " and \\\\). These are the codepoint ranges the')
    lines.append(' * reference binary escapes, derived by probing official yr')
    lines.append(' * 1.23.0 over every Unicode scalar. */')
    lines.append('static const uint32_t xx_cuckoo_yx_debug_escape[][2] = {')
    for lo, hi in ranges:
        lines.append('    {%du, %du},' % (lo, hi))
    lines.append('};')
    lines.append('')
    lines.append('#define XX_CUCKOO_YX_DEBUG_ESCAPE_COUNT \\')
    lines.append('    (sizeof(xx_cuckoo_yx_debug_escape) / sizeof(xx_cuckoo_yx_debug_escape[0]))')
    lines.append('')
    lines.append('static bool xx_cuckoo_yx_debug_is_escaped(uint32_t cp)')
    lines.append('{')
    lines.append('    size_t lo = 0, hi = XX_CUCKOO_YX_DEBUG_ESCAPE_COUNT;')
    lines.append('    while (lo < hi) {')
    lines.append('        size_t mid = lo + (hi - lo) / 2;')
    lines.append('        if (cp < xx_cuckoo_yx_debug_escape[mid][0])')
    lines.append('            hi = mid;')
    lines.append('        else if (cp > xx_cuckoo_yx_debug_escape[mid][1])')
    lines.append('            lo = mid + 1;')
    lines.append('        else')
    lines.append('            return true;')
    lines.append('    }')
    lines.append('    return false;')
    lines.append('}')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT, 'ranges:', len(ranges))

if __name__ == '__main__':
    main()
