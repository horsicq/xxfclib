/* xx_shar_extractor.c - search raw data for SHAR.
 *
 * Scans for:
 *   23 21 2F 62 69 6E 2F 73 68 at +0  ("#!.bin.sh")
 *   23 21 20 2F 62 69 6E 2F 73 68 at +0  ("#! .bin.sh")
 *   23 20 54 68 69 73 20 69 73 20 61 20 73 68 65 6C 6C 20 61 72 63 68 69 76 65 at +0  ("# This is a shell archive")
 * Offset 0 is always tried as well.
 * Each candidate must be accepted by the shar reader, which also measures it,
 * and named by the detector, both on a view that starts at the candidate.
 * See xx_format_extractor_engine.h.
 *
 * GENERATED by gen_extractors.py from the detector's prefilters.
 */

#include "../xx_format_extractor_engine.h"
#include "xxfclib/formats/shar/xx_shar.h"

static const uint8_t k_anchor0[] = { 0x23, 0x21, 0x2F, 0x62, 0x69, 0x6E, 0x2F, 0x73, 0x68 };
static const uint8_t k_anchor1[] = { 0x23, 0x21, 0x20, 0x2F, 0x62, 0x69, 0x6E, 0x2F, 0x73, 0x68 };
static const uint8_t k_anchor2[] = { 0x23, 0x20, 0x54, 0x68, 0x69, 0x73, 0x20, 0x69, 0x73, 0x20, 0x61, 0x20, 0x73, 0x68, 0x65, 0x6C, 0x6C, 0x20, 0x61, 0x72, 0x63, 0x68, 0x69, 0x76, 0x65 };

static const xx_format_search_anchor k_anchors[] = {
    { k_anchor0, sizeof(k_anchor0), 0U },
    { k_anchor1, sizeof(k_anchor1), 0U },
    { k_anchor2, sizeof(k_anchor2), 0U },
};

static const xx_file_type_t k_types[] = { XX_FILE_TYPE_SHAR };

static Abstractformat *xx_shar_search_open(xx_io_device *window) {
    xx_shar *reader = xx_shar_create(window, 0);
    return reader ? &reader->format : NULL;
}

static void xx_shar_search_close(Abstractformat *format) {
    /* The format is the first member, so this is the reader itself. */
    xx_shar_free((xx_shar *)format);
}

static const xx_format_search_desc k_desc = {
    k_types, sizeof(k_types) / sizeof(k_types[0]),
    k_anchors, sizeof(k_anchors) / sizeof(k_anchors[0]),
    xx_shar_search_open, xx_shar_search_close
};

static xx_format_search_state *xx_shar_create_format_search(
    xx_format_extractor *self, xx_io_device *device, const xx_list_s *options,
    xx_pd_struct *pd) {
    (void)self;
    return xx_format_search_create(&k_desc, device, options, pd);
}

static const xx_format_search_info *xx_shar_get_current_format_info(
    xx_format_extractor *self, xx_format_search_state *state) {
    (void)self;
    return xx_format_search_current(state);
}

static bool xx_shar_format_search_find_next(xx_format_extractor *self,
                                          xx_format_search_state *state,
                                          xx_pd_struct *pd) {
    (void)self;
    return xx_format_search_find_next(state, pd);
}

static void xx_shar_free_format_search(xx_format_extractor *self,
                                     xx_format_search_state *state) {
    (void)self;
    xx_format_search_free(state);
}

xx_format_extractor xx_shar_extractor = {
    xx_shar_create_format_search,
    xx_shar_get_current_format_info,
    xx_shar_format_search_find_next,
    xx_shar_free_format_search
};
