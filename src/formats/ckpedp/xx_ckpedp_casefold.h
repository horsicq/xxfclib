static uint32_t ce_fold(uint32_t c) {
    size_t lo = 0U, hi = sizeof(g_ce_fold) / sizeof(g_ce_fold[0]);
    if (c < 0x80U) return (c >= 'a' && c <= 'z') ? c - 0x20U : c;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2U;
        const ce_fold_run *r = &g_ce_fold[mid];
        if (c < r->start) {
            hi = mid;
        } else if (c > r->start + (uint32_t)(r->count - 1U) * r->step) {
            lo = mid + 1U;
        } else {
            if ((c - r->start) % r->step != 0U) return c;
            return (uint32_t)((int64_t)c + r->delta);
        }
    }
    return c;
}


